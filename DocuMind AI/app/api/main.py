def _ensure_upload_directory() -> Path:
    """Ensure the upload directory exists and return its resolved path."""
    upload_dir = settings.RAW_DATA_DIR / "uploads"
    upload_dir.mkdir(parents=True, exist_ok=True)
    return upload_dir


def _save_upload_file(file: UploadFile) -> Path:
    """Safely validate, sanitize, and persist an uploaded file to disk.

    Args:
        file: Uploaded file from the HTTP request.

    Returns:
        Path: Path to the saved file on disk.

    Raises:
        HTTPException: If file is missing, empty, or has an unsupported extension.
    """
    if not file.filename:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Uploaded file must have a valid filename.",
        )

    # Sanitize filename (strip directory traversal characters)
    original_name = Path(file.filename).name
    ext = Path(original_name).suffix.lower()

    if ext not in SUPPORTED_EXTENSIONS:
        formatted_supported = ", ".join(sorted(SUPPORTED_EXTENSIONS))
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Unsupported file format '{ext}'. Supported formats: {formatted_supported}",
        )

    try:
        contents = file.file.read()
    except Exception as exc:
        logger.error("Failed to read uploaded file '%s': %s", original_name, exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to read uploaded file.",
        ) from exc
    finally:
        file.file.close()

    # Verify that file is not empty
    if not contents or len(contents) == 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The uploaded file is empty.",
        )

    upload_dir = _ensure_upload_directory()
    unique_filename = f"{uuid.uuid4().hex}_{original_name}"
    target_path = upload_dir / unique_filename

    try:
        target_path.write_bytes(contents)
    except Exception as exc:
        logger.error("Failed to save uploaded file '%s': %s", original_name, exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to store uploaded file on the server.",
        ) from exc

    return target_path


def _load_and_preprocess_document(file_path: Path) -> ProcessedDocument:
    """Run the standard ingestion pipeline: load, OCR (if image), and preprocess.

    Args:
        file_path: Path to the saved document.

    Returns:
        ProcessedDocument: Cleaned and structured document.

    Raises:
        HTTPException: If any step of document extraction fails.
    """
    loader = get_document_loader()
    ocr = get_ocr_processor()
    preprocessor = get_text_preprocessor()

    try:
        raw_doc = loader.load(file_path)
        ocr_doc = ocr.process(raw_doc)
        processed_doc = preprocessor.process(ocr_doc)
        return processed_doc
    except (FileNotFoundError, ValueError) as exc:
        logger.warning("Document processing error for '%s': %s", file_path.name, exc)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(exc),
        ) from exc
    except Exception as exc:
        logger.error("Unexpected error loading document '%s': %s", file_path.name, exc)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to process document content.",
        ) from exc


