class HealthResponse(BaseModel):
    """Health check status response payload."""

    status: str = Field(default="healthy", description="Operational status of the API")
    service: str = Field(default="documind-ai", description="Service identifier")


class DocumentUploadResponse(BaseModel):
    """Response returned upon successful document upload, processing, and indexing."""

    message: str = Field(..., description="Status summary message")
    document_id: str = Field(..., description="Unique identifier generated for the document")
    filename: str = Field(..., description="Original name of the uploaded document")
    document_type: str = Field(..., description="Extension or format type of the document")
    total_pages: int = Field(..., description="Total pages parsed in the document")
    chunks_indexed: int = Field(..., description="Number of text chunks embedded and stored in FAISS")


class AgentQueryRequest(BaseModel):
    """Payload for autonomous document analysis agent queries."""

    question: str = Field(..., min_length=1, description="Question or task instruction for the agent")
    document_ids: list[str] | None = Field(
        default=None,
        description="Optional list of document IDs to scope retrieval",
    )
    document_text: str | None = Field(
        default=None,
        description="Optional full document text (required when requesting structured extraction)",
    )
    document_id: str | None = Field(
        default=None,
        description="Optional primary document ID",
    )
    filename: str | None = Field(
        default=None,
        description="Optional primary document filename",
    )
    document_type: str | None = Field(
        default=None,
        description="Optional document category or classification hint",
    )


class AgentQueryResponse(BaseModel):
    """Response returned by the autonomous document analysis agent."""

    answer: str = Field(..., description="Grounded answer or extraction result generated by the agent")


